import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { inspectConnectivity } from '../scripts/inspect_connectivity.mjs';
import { schdoc } from './altium-fixture.mjs';

function annotation(n, symbol, component, physical, channel, document=channel+'.SchDoc') {
  return `LogicalDesignator${n}=R1\nLogicalPartID${n}=1\nDocumentName${n}=${document}\nChannelName${n}=${channel}\nUniqueID${n}=\\${symbol}\\${component}\nPhysicalDesignator${n}=${physical}\n`;
}
async function fixture(t, { ports=[true,true], mode=2, stale=false }={}) {
  const dir=await mkdtemp(path.join(os.tmpdir(),'hw-hierarchy-'));
  t.after(()=>rm(dir,{recursive:true,force:true}));
  const design=path.join(dir,'Board.PrjPcb');
  await writeFile(design, `[Design]\nHierarchyMode=${mode}\n[Document1]\nDocumentPath=Root.SchDoc\n[Document2]\nDocumentPath=A.SchDoc\n[Document3]\nDocumentPath=B.SchDoc\n`);
  const root=[];
  for (const [i,name] of ['A','B'].entries()) {
    const owner=root.length, x=100+200*i;
    root.push(`|RECORD=15|UniqueID=SYM${name}|Location.X=${x}|Location.Y=100|XSize=100|YSize=100|`,
      `|RECORD=32|OwnerIndex=${owner}|Text=${name}|`, `|RECORD=33|OwnerIndex=${owner}|Text=${name}.SchDoc|`,
      `|RECORD=16|OwnerIndex=${owner}|Name=VDD|Side=0|DistanceFromTop=0|`,
      `|RECORD=25|Text=RAIL_${name}|Location.X=${x}|Location.Y=100|`);
    await writeFile(path.join(dir,name+'.SchDoc'),schdoc([
      `|RECORD=1|UniqueID=PART${name}|CurrentPartId=1|`, '|RECORD=34|OwnerIndex=0|Text=R1|',
      '|RECORD=2|OwnerIndex=0|Designator=1|Location.X=100|Location.Y=100|PinLength=0|',
      '|RECORD=17|Text=VDD|Location.X=100|Location.Y=100|',
      ...(ports[i] ? ['|RECORD=18|Name=VDD|Location.X=100|Location.Y=100|Width=0|'] : [])]));
  }
  await writeFile(path.join(dir,'Root.SchDoc'),schdoc(root));
  const annotationPath=path.join(dir,'Board.Annotation');
  const text='[DesignatorManager]\n'+annotation(0,stale?'OLDSYM':'SYMA','PARTA','R11','A')+annotation(1,'SYMB','PARTB','R12','B');
  await writeFile(annotationPath,text);
  return {dir,design,annotationPath,text};
}

test('annotation prevents equal logical references on different sheets from collapsing',async t=>{
  const f=await fixture(t); const report=await inspectConnectivity(f.design);
  assert.deepEqual(report.connections,[{refdes:'R11',pin:'1',net:'RAIL_A'},{refdes:'R12',pin:'1',net:'RAIL_B'}]);
  assert.equal(report.physical_identities.length,2);
});
test('hierarchical port-connected power stays separate from a same-named global supply',async t=>{
  const f=await fixture(t,{ports:[true,false]}); const r=await inspectConnectivity(f.design);
  assert.deepEqual(r.connections,[{refdes:'R11',pin:'1',net:'RAIL_A'},{refdes:'R12',pin:'1',net:'VDD'}]);
});
test('ordinary/global power joins while Strict Hierarchical power stays separate',async t=>{
  for (const options of [{ports:[false,false]},{mode:3}]) {
    const f=await fixture(t,options); const r=await inspectConnectivity(f.design);
    assert.equal(r.connections[0].net,r.connections[1].net);
  }
  const f=await fixture(t,{mode:4,ports:[false,false]}); const r=await inspectConnectivity(f.design);
  assert.notEqual(r.connections[0].net,r.connections[1].net);
});
test('replaced sheet symbol matches stable component UID plus document and channel',async t=>{
  const f=await fixture(t,{stale:true}); const r=await inspectConnectivity(f.design);
  assert.equal(r.physical_identities.find(p=>p.refdes==='R11').basis,'saved_annotation_component_uid_and_channel');
  assert.equal(r.connections.find(c=>c.refdes==='R11').net,'RAIL_A');
});
test('stale component UID, ambiguous rows and colliding physical designators fail closed',async t=>{
  for (const [change,pattern] of [
    [s=>s.replace('PARTA','MISSING'),/Unresolved|collision/],
    [s=>s+annotation(2,'SYMA','PARTA','R99','A'),/Ambiguous/],
    [s=>s.replace('PhysicalDesignator1=R12','PhysicalDesignator1=R11'),/collision/],
  ]) {
    const f=await fixture(t); await writeFile(f.annotationPath,change(f.text));
    await assert.rejects(inspectConnectivity(f.design),pattern);
  }
});
test('incomplete annotation and annotated assembly variants are refused',async t=>{
  const f=await fixture(t);
  await writeFile(f.annotationPath,'[DesignatorManager]\nPhysicalDesignator0=R11\n');
  await assert.rejects(inspectConnectivity(f.design),/Incomplete/);
  await writeFile(f.annotationPath,f.text);
  await writeFile(f.design,(await readFile(f.design,'utf8'))+'[ProjectVariant1]\nDescription=Production\nVariationCount=0\n');
  await assert.rejects(inspectConnectivity(f.design,'Production'),/assembly variants requires native qualification/);
});
test('autogenerated isolated-pin names use physical identity',async t=>{
  const f=await fixture(t);
  for (const name of ['A','B']) await writeFile(path.join(f.dir,name+'.SchDoc'),schdoc([
    `|RECORD=1|UniqueID=PART${name}|CurrentPartId=1|`, '|RECORD=34|OwnerIndex=0|Text=R1|',
    '|RECORD=2|OwnerIndex=0|Designator=1|Location.X=100|Location.Y=100|PinLength=0|']));
  const r=await inspectConnectivity(f.design);
  assert.deepEqual(r.connections,[{refdes:'R11',pin:'1',net:'NetR11_1'},{refdes:'R12',pin:'1',net:'NetR12_1'}]);
});
test('repeated channels use annotation room identity without double-appending suffixes',async t=>{
  const f=await fixture(t);
  await writeFile(f.design,'[Design]\nHierarchyMode=2\n[Document1]\nDocumentPath=Root.SchDoc\n[Document2]\nDocumentPath=A.SchDoc\n');
  await writeFile(path.join(f.dir,'Root.SchDoc'),schdoc(['|RECORD=15|UniqueID=REPEAT|','|RECORD=32|OwnerIndex=0|Text=Repeat(CH,1,2)|','|RECORD=33|OwnerIndex=0|Text=A.SchDoc|']));
  await writeFile(path.join(f.dir,'A.SchDoc'),schdoc(['|RECORD=1|UniqueID=PARTA|CurrentPartId=1|','|RECORD=34|OwnerIndex=0|Text=R1|','|RECORD=2|OwnerIndex=0|Designator=1|Location.X=100|Location.Y=100|PinLength=0|']));
  await writeFile(f.annotationPath,'[DesignatorManager]\n'+annotation(0,'REPEAT','PARTA','R101','CH1','A.SchDoc')+annotation(1,'REPEAT','PARTA','R102','CH2','A.SchDoc'));
  const r=await inspectConnectivity(f.design);
  assert.deepEqual(r.connections,[{refdes:'R101',pin:'1',net:'NetR101_1'},{refdes:'R102',pin:'1',net:'NetR102_1'}]);
});
test('annotated multi-part symbols preserve both parts under the same physical reference',async t=>{
  const f=await fixture(t);
  await writeFile(path.join(f.dir,'A.SchDoc'),schdoc([
    '|RECORD=1|UniqueID=PARTA|CurrentPartId=1|','|RECORD=34|OwnerIndex=0|Text=R1|',
    '|RECORD=2|OwnerIndex=0|OwnerPartId=1|Designator=1|Location.X=100|Location.Y=100|PinLength=0|',
    '|RECORD=1|UniqueID=PARTA2|CurrentPartId=2|','|RECORD=34|OwnerIndex=3|Text=R1|',
    '|RECORD=2|OwnerIndex=3|OwnerPartId=2|Designator=2|Location.X=200|Location.Y=100|PinLength=0|']));
  await writeFile(f.annotationPath,f.text+annotation(2,'SYMA','PARTA2','R11','A').replace('LogicalPartID2=1','LogicalPartID2=2'));
  const r=await inspectConnectivity(f.design);
  assert.deepEqual(Object.keys(r.components.R11.pins).sort(),['1','2']);
  assert.equal(r.physical_identities.filter(p=>p.refdes==='R11').length,2);
});
test('cyclic and missing sheet references do not silently invent roots',async t=>{
  const f=await fixture(t);
  await writeFile(path.join(f.dir,'A.SchDoc'),schdoc(['|RECORD=15|UniqueID=CYCLE|','|RECORD=32|OwnerIndex=0|Text=Loop|','|RECORD=33|OwnerIndex=0|Text=Root.SchDoc|']));
  await assert.rejects(inspectConnectivity(f.design),/Cyclic/);
  await writeFile(path.join(f.dir,'A.SchDoc'),schdoc(['|RECORD=15|','|RECORD=33|OwnerIndex=0|Text=Missing.SchDoc|']));
  await assert.rejects(inspectConnectivity(f.design),/Missing hierarchy sheet/);
});
